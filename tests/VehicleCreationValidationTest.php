        $this->assert(str_contains($viewContent, 'id="vf_type_error"'), 'Must have inline error container for type');
        $this->assert(str_contains($viewContent, 'id="vf_price_per_day_error"'), 'Must have inline error container for price_per_day');
        $this->assert(str_contains($viewContent, 'id="vf_location_error"'), 'Must have inline error container for location');
        $this->assert(str_contains($viewContent, 'id="vf_image_error"'), 'Must have inline error container for image');
        $this->assert(str_contains($viewContent, 'id="vf_description_error"'), 'Must have inline error container for description');

        // Description counter and client-side validator
        $this->assert(str_contains($viewContent, 'id="vf_desc_counter"'), 'Must contain description character counter');
        $this->assert(str_contains($viewContent, 'validateClientForm'), 'Must contain validateClientForm script');
        $this->assert(str_contains($viewContent, 'e.preventDefault()'), 'Form submission must be prevented when invalid');
    }
