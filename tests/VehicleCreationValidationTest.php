<?php

declare(strict_types=1);

namespace Tests;

require_once __DIR__ . '/../bootstrap.php';

use App\Controllers\RentalController;
use App\Models\Vehicle;

final class VehicleCreationValidationTest
{
    private int $passed = 0;
    private int $failed = 0;

    public function run(): bool
    {
        echo "========================================================\n";
        echo " GuideMate Vehicle Creation Validation Test Suite\n";
        echo "========================================================\n\n";

        $this->runTest('testMissingRequiredFieldsFailValidation', [$this, 'testMissingRequiredFieldsFailValidation']);
        $this->runTest('testWhitespaceOnlyFieldsFailValidation', [$this, 'testWhitespaceOnlyFieldsFailValidation']);
        $this->runTest('testModelYearValidation', [$this, 'testModelYearValidation']);
        $this->runTest('testVehicleTypeCategoryValidation', [$this, 'testVehicleTypeCategoryValidation']);
        $this->runTest('testDailyRentalRateValidation', [$this, 'testDailyRentalRateValidation']);
        $this->runTest('testDescriptionLengthValidation', [$this, 'testDescriptionLengthValidation']);
        $this->runTest('testCoverPhotoValidationOnCreateAndEdit', [$this, 'testCoverPhotoValidationOnCreateAndEdit']);
        $this->runTest('testSuccessfulValidationAndSanitization', [$this, 'testSuccessfulValidationAndSanitization']);
        $this->runTest('testAutoGeneratedDisplayTitleWhenBlank', [$this, 'testAutoGeneratedDisplayTitleWhenBlank']);
        $this->runTest('testViewTemplateFormContainsAllRequiredMarkersAndValidation', [$this, 'testViewTemplateFormContainsAllRequiredMarkersAndValidation']);

        echo "\n--------------------------------------------------------\n";
        echo sprintf("Results: %d passed, %d failed\n", $this->passed, $this->failed);
        echo "--------------------------------------------------------\n";

        return $this->failed === 0;
    }

    private function runTest(string $name, callable $test): void
    {
        try {
            $test();
            $this->passed++;
            echo " [PASS] {$name}\n";
        } catch (\Throwable $e) {
            $this->failed++;
            echo " [FAIL] {$name}: {$e->getMessage()}\n";
        }
    }

    private function assert(bool $condition, string $message): void
    {
        if (!$condition) {
            throw new \RuntimeException($message);
        }
    }

    public function testMissingRequiredFieldsFailValidation(): void
    {
        $emptyInput = [];
        $result = RentalController::validateVehicleInputs($emptyInput, null, null);

        $errors = $result['errors'];
        $this->assert(isset($errors['make']), 'Missing make must produce validation error');
        $this->assert(isset($errors['model']), 'Missing model must produce validation error');
        $this->assert(isset($errors['year']), 'Missing year must produce validation error');
        $this->assert(isset($errors['type']), 'Missing type must produce validation error');
        $this->assert(isset($errors['price_per_day']), 'Missing price_per_day must produce validation error');
        $this->assert(isset($errors['location']), 'Missing location must produce validation error');
        $this->assert(isset($errors['description']), 'Missing description must produce validation error');
        $this->assert(isset($errors['image']), 'Missing image on create must produce validation error');
    }

    public function testWhitespaceOnlyFieldsFailValidation(): void
    {
        $whitespaceInput = [
            'make' => "   \t  ",
            'model' => " \n  ",
            'year' => 2024,
            'type' => 'Scooter',
            'price_per_day' => 500,
            'location' => "   ",
            'description' => "                   ", // 19 spaces
        ];

        $result = RentalController::validateVehicleInputs($whitespaceInput, null, null);
        $errors = $result['errors'];

        $this->assert(isset($errors['make']), 'Whitespace-only make must fail');
        $this->assert(isset($errors['model']), 'Whitespace-only model must fail');
        $this->assert(isset($errors['location']), 'Whitespace-only location must fail');
        $this->assert(isset($errors['description']), 'Whitespace-only description must fail');
    }

    public function testModelYearValidation(): void
    {
        $base = [
            'make' => 'Honda',
            'model' => 'Click 125i',
            'type' => 'Scooter',
            'price_per_day' => 500,
            'location' => 'Cebu City',
            'description' => 'A valid description that is at least 20 characters long.',
        ];

        // 1. Non-numeric
        $r1 = RentalController::validateVehicleInputs(array_merge($base, ['year' => 'invalid']), null, 1);
        $this->assert(isset($r1['errors']['year']), 'Non-numeric year must fail');

        // 2. Year before 1980
        $r2 = RentalController::validateVehicleInputs(array_merge($base, ['year' => 1970]), null, 1);
        $this->assert(isset($r2['errors']['year']), 'Year before 1980 must fail');

        // 3. Year far in future
        $r3 = RentalController::validateVehicleInputs(array_merge($base, ['year' => 2099]), null, 1);
        $this->assert(isset($r3['errors']['year']), 'Far future year must fail');

        // 4. Valid year
        $r4 = RentalController::validateVehicleInputs(array_merge($base, ['year' => 2024]), null, 1);
        $this->assert(!isset($r4['errors']['year']), 'Valid year 2024 must pass');
    }

    public function testVehicleTypeCategoryValidation(): void
    {
        $base = [
            'make' => 'Honda',
            'model' => 'Click 125i',
            'year' => 2024,
            'price_per_day' => 500,
            'location' => 'Cebu City',
            'description' => 'A valid description that is at least 20 characters long.',
        ];

        // 1. Invalid category
        $r1 = RentalController::validateVehicleInputs(array_merge($base, ['type' => 'Helicopter']), null, 1);
        $this->assert(isset($r1['errors']['type']), 'Unlisted vehicle type must fail');

        // 2. Each allowed category in Vehicle::TYPES must pass
        foreach (Vehicle::TYPES as $validType) {
            $r2 = RentalController::validateVehicleInputs(array_merge($base, ['type' => $validType]), null, 1);
            $this->assert(!isset($r2['errors']['type']), "Vehicle type '{$validType}' must pass validation");
        }
    }

    public function testDailyRentalRateValidation(): void
    {
        $base = [
            'make' => 'Honda',
            'model' => 'Click 125i',
            'year' => 2024,
            'type' => 'Scooter',
            'location' => 'Cebu City',
            'description' => 'A valid description that is at least 20 characters long.',
        ];

        // 1. Zero or negative
        $r1 = RentalController::validateVehicleInputs(array_merge($base, ['price_per_day' => 0]), null, 1);
        $this->assert(isset($r1['errors']['price_per_day']), 'Rate of 0 must fail');

        $r2 = RentalController::validateVehicleInputs(array_merge($base, ['price_per_day' => -100]), null, 1);
        $this->assert(isset($r2['errors']['price_per_day']), 'Negative rate must fail');

        // 2. Below minimum ₱50
        $r3 = RentalController::validateVehicleInputs(array_merge($base, ['price_per_day' => 20]), null, 1);
        $this->assert(isset($r3['errors']['price_per_day']), 'Rate below ₱50 must fail');

        // 3. Above max ₱500,000
        $r4 = RentalController::validateVehicleInputs(array_merge($base, ['price_per_day' => 600000]), null, 1);
        $this->assert(isset($r4['errors']['price_per_day']), 'Rate exceeding ₱500,000 must fail');

        // 4. Valid rate
        $r5 = RentalController::validateVehicleInputs(array_merge($base, ['price_per_day' => 650]), null, 1);
        $this->assert(!isset($r5['errors']['price_per_day']), 'Rate of ₱650 must pass');
    }

    public function testDescriptionLengthValidation(): void
    {
        $base = [
            'make' => 'Honda',
            'model' => 'Click 125i',
            'year' => 2024,
            'type' => 'Scooter',
            'price_per_day' => 500,
            'location' => 'Cebu City',
        ];

        // 1. Fewer than 20 characters
        $shortDesc = 'Brand new scooter'; // 17 chars
        $r1 = RentalController::validateVehicleInputs(array_merge($base, ['description' => $shortDesc]), null, 1);
        $this->assert(isset($r1['errors']['description']), 'Description under 20 chars must fail');
        $this->assert(str_contains($r1['errors']['description'], '17 characters'), 'Error should indicate current character count');

        // 2. Exactly 20 characters
        $exact20 = '12345678901234567890';
        $r2 = RentalController::validateVehicleInputs(array_merge($base, ['description' => $exact20]), null, 1);
        $this->assert(!isset($r2['errors']['description']), 'Description with 20 chars must pass');

        // 3. Comfortable long description
        $longDesc = '2024 Yamaha NMAX in pristine condition with dual helmets, full tank, phone mount, and roadside assistance.';
        $r3 = RentalController::validateVehicleInputs(array_merge($base, ['description' => $longDesc]), null, 1);
        $this->assert(!isset($r3['errors']['description']), 'Long description must pass');
    }

    public function testCoverPhotoValidationOnCreateAndEdit(): void
    {
        $validInput = [
            'make' => 'Honda',
            'model' => 'Click 125i',
            'year' => 2024,
            'type' => 'Scooter',
            'price_per_day' => 500,
            'location' => 'Cebu City',
            'description' => 'A valid description that is at least 20 characters long.',
        ];

        // 1. On Create (null vehicleId): no file provided
        $rCreateNoFile = RentalController::validateVehicleInputs($validInput, null, null);
        $this->assert(isset($rCreateNoFile['errors']['image']), 'New vehicle listing must require primary cover photo');

        // 2. On Create: invalid file extension
        $badFile = [
            'name' => 'malicious.exe',
            'type' => 'application/x-msdownload',
            'size' => 2048,
            'tmp_name' => sys_get_temp_dir() . '/test.exe',
            'error' => UPLOAD_ERR_OK,
        ];
        $rBadExt = RentalController::validateVehicleInputs($validInput, $badFile, null);
        $this->assert(isset($rBadExt['errors']['image']), 'Executable file must be rejected as cover photo');

        // 3. On Create: oversized file (> 5MB)
        $bigFile = [
            'name' => 'giant_scooter.jpg',
            'type' => 'image/jpeg',
            'size' => 6 * 1024 * 1024, // 6 MB
            'tmp_name' => sys_get_temp_dir() . '/giant.jpg',
            'error' => UPLOAD_ERR_OK,
        ];
        $rBigFile = RentalController::validateVehicleInputs($validInput, $bigFile, null);
        $this->assert(isset($rBigFile['errors']['image']), 'Photo exceeding 5MB must be rejected');

        // 4. On Create: valid JPG file
        $goodFile = [
            'name' => 'scooter_front.jpg',
            'type' => 'image/jpeg',
            'size' => 800 * 1024, // 800 KB
            'tmp_name' => sys_get_temp_dir() . '/scooter.jpg',
            'error' => UPLOAD_ERR_OK,
        ];
        $rGood = RentalController::validateVehicleInputs($validInput, $goodFile, null);
        $this->assert(!isset($rGood['errors']['image']), 'Valid JPG file must pass image validation');

        // 5. On Edit (vehicleId = 42): no new file provided is permitted (preserves existing photo)
        $rEditNoFile = RentalController::validateVehicleInputs($validInput, null, 42);
        $this->assert(!isset($rEditNoFile['errors']['image']), 'Editing existing vehicle without new photo must pass');
    }

    public function testSuccessfulValidationAndSanitization(): void
    {
        $goodFile = [
            'name' => 'nmax.webp',
            'type' => 'image/webp',
            'size' => 450 * 1024,
            'tmp_name' => sys_get_temp_dir() . '/nmax.webp',
            'error' => UPLOAD_ERR_OK,
        ];

        $payload = [
            'make' => '  Yamaha  ',
            'model' => '  NMAX 155 ABS  ',
            'year' => '2024',
            'type' => 'Scooter',
            'name' => 'Premium South Cebu Scooter',
            'price_per_day' => '850.00',
            'location' => '  Moalboal, South Cebu  ',
            'address' => 'Panagsama Beach Road',
            'description' => '2024 Yamaha NMAX in pristine condition with dual helmets, comprehensive insurance, and phone mount.',
            'specs' => ['Automatic Transmission', 'Helmets Included', 'Self-Drive'],
            'custom_spec' => 'Free Airport Delivery',
        ];

        $result = RentalController::validateVehicleInputs($payload, $goodFile, null);

        $this->assert($result['errors'] === [], 'All valid inputs must yield 0 validation errors');
        $data = $result['data'];

        $this->assert($data['make'] === 'Yamaha', 'Make must be trimmed');
        $this->assert($data['model'] === 'NMAX 155 ABS', 'Model must be trimmed');
        $this->assert($data['year'] === 2024, 'Year must be integer');
        $this->assert($data['price_per_day'] === 850.0, 'Price must be float');
        $this->assert($data['location'] === 'Moalboal, South Cebu', 'Location must be trimmed');
        $this->assert($data['name'] === 'Premium South Cebu Scooter', 'Custom display title preserved');
        $this->assert(in_array('Free Airport Delivery', $data['specs'], true), 'Custom spec must be appended to specs');
    }

    public function testAutoGeneratedDisplayTitleWhenBlank(): void
    {
        $goodFile = [
            'name' => 'vios.png',
            'type' => 'image/png',
            'size' => 500 * 1024,
            'tmp_name' => sys_get_temp_dir() . '/vios.png',
            'error' => UPLOAD_ERR_OK,
        ];

        $payload = [
            'make' => 'Toyota',
            'model' => 'Vios 1.3 XLE',
            'year' => 2023,
            'type' => 'Sedan',
            'name' => '   ', // Blank title
            'price_per_day' => 1800,
            'location' => 'Cebu City · IT Park',
            'description' => 'Clean 5-seater sedan with automatic transmission, cold A/C, and unlimited mileage.',
        ];

        $result = RentalController::validateVehicleInputs($payload, $goodFile, null);
        $this->assert($result['errors'] === [], 'Must pass validation');
        $this->assert($result['data']['name'] === '2023 Toyota Vios 1.3 XLE', 'Title must default to Year Make Model');
    }

