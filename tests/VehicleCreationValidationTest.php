        $this->assert(str_contains($viewContent, 'Model Year <span class="req"'), 'Year must be marked required with asterisk');
        $this->assert(str_contains($viewContent, 'Vehicle Type <span class="req"'), 'Type must be marked required with asterisk');
        $this->assert(str_contains($viewContent, 'Rental Rate per Day (PHP) <span class="req"'), 'Rate must be marked required with asterisk');
        $this->assert(str_contains($viewContent, 'Pickup Area / Island Hub <span class="req"'), 'Location must be marked required with asterisk');
        $this->assert(str_contains($viewContent, 'Primary Cover Photo <span id="vf_image_req" class="req"'), 'Cover photo must be marked required with asterisk');
        $this->assert(str_contains($viewContent, 'Vehicle Description &amp; Rental Terms <span class="req"'), 'Description must be marked required with asterisk');

        // Inline field error elements
        $this->assert(str_contains($viewContent, 'id="vf_make_error"'), 'Must have inline error container for make');
        $this->assert(str_contains($viewContent, 'id="vf_model_error"'), 'Must have inline error container for model');
